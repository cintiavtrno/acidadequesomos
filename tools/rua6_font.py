def width(s, gap=1): return len(s) * (5 + gap) - gap
def text(c, x, y, s, col, gap=1):
    for ch in s.upper():
        g = G.get(ch, G[' '])
        for j, row in enumerate(g):
            for i, v in enumerate(row):
                if v == '#': c.pset(x + i, y + j, col)
        x += 5 + gap
    return x
